// Retrouve une activité par sa clé de progression « <session>:<activité> »
// (ex. 'ch5-s0:b'). Sert aux liens croisés débranché ↔ écran.
export function findActivity(key) {
  if (!key) return null
  const [sid, aid] = key.split(':')
  for (const ch of CHAPTERS) {
    const s = ch.sessions.find((x) => x.id === sid)
    if (s) {
      const a = s.activities.find((x) => x.id === aid)
      return a ? { chapter: ch, session: s, activity: a } : null
    }
  }
  return null
}

export function findChapter(id) {
  return CHAPTERS.find((c) => c.id === id)
}

